"""Seeded synthetic workloads for the Myelinated Memory benchmark.

Deterministic by construction: everything derives from ``random.Random(seed)``,
so two runs of the same seed produce byte-identical scenarios. Scenario ids are
stable (``syn-<kind>-<i>``), which lets results be diffed across runs.

Query kinds and what each one stresses
--------------------------------------
``lookup``        one specific fact buried among similarly shaped distractors.
``preference``    durable user preferences versus high-volume ephemeral trivia.
``continuity``    task state set in session 1 and needed much later, reachable
                  only through prior *access*, never through recency.
``contradiction`` a value is updated; the superseded memory must not surface.
``budget``        300+ memories competing for a 2,200-character context budget.
``coldstart``     memories that were never accessed, so there is no Hebbian
                  signal at all to rank on.
``adversarial``   important-but-never-accessed memories versus frequently
                  accessed trivia, i.e. access frequency disagrees with value.

Ground-truth invariants (validated by ``__main__``)
---------------------------------------------------
1. Every id in ``Query.evidence_ids`` was created by an ``add`` event at or
   before ``Query.session``, and is still present when the query runs.
2. Every id in ``Query.stale_ids`` was also created before the query; staleness
   is *emergent* — the superseding memory is the one that keeps getting
   accessed, while the superseded one is never touched again and decays.
3. ``events`` are sorted by non-decreasing ``day``; a query's ``session`` is at
   least the day of every memory in its evidence.
4. Ids are unique within a scenario.

Staleness suites
----------------
``staleness_suite`` and ``decay_only_staleness_suite`` are generated by ONE
shared builder and differ only in whether retire events are emitted. That split
is deliberate (board ruling BM-003): supersession and decay are different
mechanisms and a supersession win must never be reported as a decay win. The
``contradiction`` kind above cannot measure either, because its store is small
enough that every arm surfaces the stale fact and the replacement together.

Nothing here calls an engine or touches the network.
"""

from __future__ import annotations

import random
from typing import Dict, List, Optional, Sequence, Set, Tuple

from common import Event, Query, QUERY_KINDS, Scenario, jaccard, tokenize

__all__ = ["generate", "scalability_corpus", "KIND_BUILDERS",
           "staleness_suite", "decay_only_staleness_suite"]


# ----------------------------------------------------------------- helpers
def _add(day: float, mem_id: str, content: str, category: str = "general",
         protected: bool = False) -> Event:
    return Event(op="add", day=float(day), id=mem_id, content=content,
                 category=category, protected=protected)


def _access(day: float, mem_id: str) -> Event:
    return Event(op="access", day=float(day), id=mem_id)


def _query(session: int, qid: str, question: str, answer: str, evidence: Sequence[str],
           stale: Optional[Sequence[str]] = None, kind: str = "lookup",
           check: str = "contains") -> Query:
    return Query(id=qid, query=question, answer=answer, evidence_ids=list(evidence),
                 stale_ids=list(stale or []), session=int(session), kind=kind,
                 answer_check=check)


# ------------------------------------------------------- background noise
_FRAMES = (
    "While working on {area}, we confirmed that {thing} {verb} {detail}.",
    "Follow-up on {area}: {thing} {verb} {detail}.",
    "{area} note: {thing} {verb} {detail}.",
)
_AREAS = (
    "the ingest pipeline", "the billing worker", "the search index", "the auth service",
    "the dashboard", "the notification queue", "the mobile API", "the export job",
    "the recommendation model", "the audit log", "the scheduler", "the data warehouse",
)
_THINGS = (
    "the retry policy", "the batch size", "the shard key", "the cache TTL",
    "the connection limit", "the compression codec", "the index strategy",
    "the partition scheme", "the serialization format", "the timeout budget",
    "the backoff curve", "the replica count",
)
_VERBS = ("matters most", "should stay as it is", "was changed deliberately", "remains fragile",
          "needs a follow-up ticket", "is the current default")
_DETAILS = ("under peak load", "when the queue drains", "during the nightly run",
            "after the schema change", "in the eu region", "on the smallest instance",
            "for cold starts", "when traffic doubles", "with the new client library",
            "at high cardinality", "for long-lived sessions", "before the freeze")


def _noise_text(rng: random.Random, used: Set[Tuple]) -> Tuple[str, str, str]:
    """Return ``(text, area, thing)`` for a unique background memory."""
    for _ in range(200):
        frame = rng.randrange(len(_FRAMES))
        area = rng.randrange(len(_AREAS))
        thing = rng.randrange(len(_THINGS))
        verb = rng.randrange(len(_VERBS))
        detail = rng.randrange(len(_DETAILS))
        key = (frame, area, thing, verb, detail)
        if key in used:
            continue
        used.add(key)
        text = _FRAMES[frame].format(area=_AREAS[area], thing=_THINGS[thing],
                                     verb=_VERBS[verb], detail=_DETAILS[detail])
        return text, _AREAS[area], _THINGS[thing]
    fallback = "Note %d: %s %s %s." % (len(used), _AREAS[0], _THINGS[0], _DETAILS[0])
    return fallback, _AREAS[0], _THINGS[0]


def _noise(rng: random.Random, count: int, start_day: float, prefix: str,
           category: str = "ephemeral", used: Optional[Set[Tuple]] = None) -> List[Event]:
    used = set() if used is None else used
    out: List[Event] = []
    for i in range(count):
        text, _, _ = _noise_text(rng, used)
        out.append(_add(start_day, "%s-%d" % (prefix, i), text, category))
    return out


def _ordered(events: Sequence[Event]) -> List[Event]:
    """Sort by day, adds before accesses on the same day (invariant 3)."""
    return sorted(events, key=lambda e: (e.day, 0 if e.op == "add" else 1))


# ------------------------------------------------------------- scenarios
def _build_preference(rng: random.Random, i: int) -> Scenario:
    sid = "syn-preference-%d" % i
    prefs = [
        ("style", "User prefers concise replies: no preamble and no restating of the question."),
        ("diet", "User is vegetarian and avoids cilantro."),
        ("editor", "User works in Neovim with a hand-written lua config; VS Code suggestions are unwelcome."),
    ]
    events: List[Event] = [_add(0.0, "%s-%s" % (sid, name), text, "preference") for name, text in prefs]
    events += _noise(rng, 14, 0.0, "%s-e" % sid)
    for day, idx in ((3.0, 0), (7.0, 1), (11.0, 2), (15.0, 0), (19.0, 1)):
        events.append(_access(day, "%s-%s" % (sid, prefs[idx][0])))
    queries = [
        _query(21, "%s-q1" % sid, "How does the user want replies formatted?",
               "concise, with no preamble", ["%s-style" % sid], kind="preference"),
        _query(21, "%s-q2" % sid, "Does the user eat meat?",
               "no, vegetarian and avoids cilantro", ["%s-diet" % sid], kind="preference"),
        _query(21, "%s-q3" % sid, "Which editor should suggestions target?",
               "Neovim with a lua config, not VS Code", ["%s-editor" % sid], kind="preference"),
    ]
    return Scenario(sid, "preference", "durable preferences against ephemeral trivia",
                    _ordered(events), queries)


def _build_continuity(rng: random.Random, i: int) -> Scenario:
    sid = "syn-continuity-%d" % i
    plan, loader, api = "%s-plan" % sid, "%s-loader" % sid, "%s-api" % sid
    events: List[Event] = [
        _add(0.0, plan, "Refactor plan for app.py: (1) extract loaders, (2) extract models, "
                        "(3) extract routes. Step 2 is in progress.", "task"),
        _add(1.0, loader, "The loader extraction is merged to main as loaders.py.", "task"),
        _add(2.0, api, "Decision: the public API stays versioned under /v2 until the migration "
                       "note is published.", "general"),
    ]
    events += _noise(rng, 20, 2.0, "%s-e" % sid)
    for d in (4.0, 9.0, 17.0, 27.0, 38.0):
        events.append(_access(d, plan))
    events.append(_access(12.0, loader))
    events.append(_access(20.0, api))
    queries = [
        _query(45, "%s-q1" % sid, "Where did we leave the app.py refactor?",
               "step 2, extracting models", [plan], kind="continuity"),
        _query(45, "%s-q2" % sid, "What did we decide about API versioning?",
               "/v2 until the migration note is published", [api], kind="continuity"),
        _query(45, "%s-q3" % sid, "Is the loader extraction finished?",
               "yes, merged to main as loaders.py", [loader], kind="continuity"),
    ]
    return Scenario(sid, "continuity", "task state from session 1 needed much later",
                    _ordered(events), queries)


def _build_contradiction(rng: random.Random, i: int) -> Scenario:
    sid = "syn-contradiction-%d" % i
    if i % 2 == 0:
        old = "Deploy target for the web service is the staging cluster in eu-west."
        new = "Deploy target for the web service is now the production cluster in us-east."
        question = "Which cluster do we deploy the web service to?"
        answer = "the production cluster in us-east"
    else:
        old = "The user's home timezone is America/New_York and meetings are scheduled in that zone."
        new = "The user has relocated: the current timezone is Europe/Berlin and meetings moved with it."
        question = "What timezone is the user in now?"
        answer = "Europe/Berlin"
    oid, nid = "%s-old" % sid, "%s-new" % sid
    events: List[Event] = [_add(0.0, oid, old, "general"), _add(4.0, nid, new, "general")]
    events += _noise(rng, 12, 1.0, "%s-e" % sid)
    for d in (5.0, 8.0, 14.0, 22.0):
        events.append(_access(d, nid))
    queries = [_query(25, "%s-q1" % sid, question, answer, [nid], [oid], kind="contradiction")]
    return Scenario(sid, "contradiction", "superseded value must not surface",
                    _ordered(events), queries)


def _build_lookup(rng: random.Random, i: int) -> Scenario:
    sid = "syn-lookup-%d" % i
    facts = [
        "The internal metrics endpoint is /admin/metrics on port 9100, scraped every 30 seconds.",
        "Release artifacts are uploaded to the s3 bucket acme-releases-eu under the /nightly prefix.",
        "The staging API token is rotated by the ops bot every Monday at 06:00 UTC.",
    ]
    target = facts[i % len(facts)]
    mid = "%s-fact" % sid
    events: List[Event] = [_add(0.0, mid, target, "general")]
    events += _noise(rng, 40, 0.0, "%s-e" % sid)
    events.append(_access(6.0, mid))
    queries = [_query(9, "%s-q1" % sid, "What is the exact fact I should remember here?", target,
                      [mid], kind="lookup", check="contains")]
    return Scenario(sid, "lookup", "one fact among many distractors", _ordered(events), queries)


def _build_budget(rng: random.Random, i: int) -> Scenario:
    sid = "syn-budget-%d" % i
    hot = [
        ("style", "User's standing instruction: always show the failing assertion before the fix."),
        ("schema", "The orders table uses order_id as a UUID and does not use auto-increment."),
        ("ci", "CI runs on GitHub Actions; the lint job must pass before the test job starts."),
    ]
    events: List[Event] = [_add(0.0, "%s-%s" % (sid, name), text, "general") for name, text in hot]
    used: Set[Tuple] = set()
    for d in range(28):
        events += _noise(rng, 11, float(d), "%s-cold-%d" % (sid, d), "ephemeral", used)
    for d in range(1, 28, 2):
        for name, _ in hot:
            events.append(_access(float(d), "%s-%s" % (sid, name)))
    queries = [
        _query(30, "%s-q1" % sid, "How should I present a failing test?",
               "show the failing assertion before the fix", ["%s-style" % sid], kind="budget"),
        _query(30, "%s-q2" % sid, "What is the primary key type on the orders table?",
               "order_id is a UUID, no auto-increment", ["%s-schema" % sid], kind="budget"),
        _query(30, "%s-q3" % sid, "Which CI job has to pass first?",
               "the lint job before the test job", ["%s-ci" % sid], kind="budget"),
    ]
    return Scenario(sid, "budget", "300+ memories competing for a 2,200-char budget",
                    _ordered(events), queries)


def _build_coldstart(rng: random.Random, i: int) -> Scenario:
    sid = "syn-coldstart-%d" % i
    mid = "%s-target" % sid
    events: List[Event] = [
        _add(0.0, mid, "The nightly backup window is 02:00-02:30 UTC and must not be moved.", "general"),
    ]
    events += _noise(rng, 24, 0.0, "%s-e" % sid)
    queries = [_query(3, "%s-q1" % sid, "When is the nightly backup window?",
                      "02:00-02:30 UTC", [mid], kind="coldstart")]
    return Scenario(sid, "coldstart", "no memory was ever accessed", _ordered(events), queries)


def _build_adversarial(rng: random.Random, i: int) -> Scenario:
    sid = "syn-adversarial-%d" % i
    important = [
        ("safety", "Never run destructive database migrations without an explicit written confirmation."),
        ("identity", "The user's legal name for invoices is Tomasz Kaczmarek of Northwind Labs Ltd."),
    ]
    trivia = [
        "The build takes 47 seconds on the CI runner.",
        "The office wifi password rotates on the first Monday of the month.",
        "The demo laptop is kept in the second drawer of the white desk.",
    ]
    events: List[Event] = [_add(0.0, "%s-%s" % (sid, n), t, "identity" if n == "identity" else "general")
                           for n, t in important]
    for k, t in enumerate(trivia):
        events.append(_add(0.0, "%s-trivia-%d" % (sid, k), t, "general"))
    for d in range(1, 26):
        for k in range(len(trivia)):
            events.append(_access(float(d), "%s-trivia-%d" % (sid, k)))
    queries = [
        _query(27, "%s-q1" % sid, "What must I never do with the production database?",
               "never run destructive migrations without written confirmation",
               ["%s-safety" % sid], kind="adversarial"),
        _query(27, "%s-q2" % sid, "What name and company go on the user's invoices?",
               "Tomasz Kaczmarek, Northwind Labs Ltd.", ["%s-identity" % sid], kind="adversarial"),
    ]
    return Scenario(sid, "adversarial", "important but never accessed vs. accessed trivia",
                    _ordered(events), queries)


KIND_BUILDERS = {
    "lookup": _build_lookup,
    "preference": _build_preference,
    "continuity": _build_continuity,
    "contradiction": _build_contradiction,
    "budget": _build_budget,
    "coldstart": _build_coldstart,
    "adversarial": _build_adversarial,
}


def generate(seed: int = 0, per_kind: int = 2) -> List[Scenario]:
    """Return ``per_kind`` deterministic scenarios for every query kind."""
    rng = random.Random(seed)
    out: List[Scenario] = []
    for kind in QUERY_KINDS:
        builder = KIND_BUILDERS[kind]
        for i in range(per_kind):
            out.append(builder(rng, i))
    return out


def scalability_corpus(seed: int = 0, n_memories: int = 10000,
                       days: int = 60) -> Tuple[List[Event], List[Query]]:
    """A large store for the latency/scale test.

    ``n_memories`` adds are spread across ``days`` virtual days, most memories
    are never touched, and a Zipf-flavoured minority is accessed repeatedly. A
    handful of queries target memories drawn from that accessed minority, so a
    score-based arm has a fair signal to work with.
    """
    rng = random.Random(seed)
    # A non-positive horizon would schedule the "long tail" accesses at day -1,
    # i.e. before the memories they point at. Clamp so the corpus is always
    # replayable, whatever the caller passes.
    days = max(1, int(days))
    events: List[Event] = []
    index: List[Tuple[str, float, str, str]] = []  # (id, day, area, thing)
    used: Set[Tuple] = set()

    for k in range(n_memories):
        d = float((k * days) // max(1, n_memories))
        mid = "scale-%d" % k
        text, area, thing = _noise_text(rng, used)
        events.append(_add(d, mid, text, "general"))
        index.append((mid, d, area, thing))

    hot = rng.sample([row[0] for row in index], min(20, len(index)))
    hot_rows = [row for row in index if row[0] in set(hot)]
    for mid, created, _area, _thing in hot_rows:
        for step in (1.0, 3.0, 7.0, 14.0, 30.0):
            when = min(created + step, float(days - 1))
            if when >= created:
                events.append(_access(when, mid))
    # long tail: many memories used exactly once
    for _ in range(min(2000, n_memories)):
        mid, created, _area, _thing = index[rng.randrange(len(index))]
        when = min(created + float(rng.randrange(1, 20)), float(days - 1))
        events.append(_access(when, mid))

    queries: List[Query] = []
    for q, row in enumerate(rng.sample(hot_rows, min(5, len(hot_rows)))):
        mid, _created, area, thing = row
        queries.append(_query(days - 1, "scale-q%d" % q,
                              "What did we confirm about %s and %s?" % (thing, area),
                              thing, [mid], kind="continuity"))
    return _ordered(events), queries


# --------------------------------------------------------- staleness suites
# Design requirements, and why:
#   * the 2,200-character budget must BIND. The earlier contradiction scenarios
#     were small enough that every arm surfaced the stale fact AND its
#     replacement, so stale_leak_rate was 1.000 for every arm including flat
#     FIFO and the metric discriminated nothing.
#   * the stale fact is myelinated (accessed repeatedly) BEFORE it is
#     superseded, so a score-based arm has a real reason to keep surfacing it.
#   * the pair stays below the engine's 0.9 Jaccard duplicate threshold, so
#     duplicate collapsing can never be mistaken for staleness handling.
#   * the filler is added late enough that decay has not yet demoted it, so the
#     budget is genuinely contested when the query runs.
#   * scenario AND query ids are namespaced by mode, because ``metrics.align``
#     pairs arms by query id across the whole run - the two suites must not
#     collide or the paired statistics would silently merge them.

_STALENESS_CASES = (
    {
        "slug": "deploy",
        "old": "Deploy target for the web service is the staging cluster in eu-west.",
        "new": "Deploy target for the web service is now the production cluster in us-east.",
        "question": "Which cluster do we deploy the web service to?",
        "answer": "the production cluster in us-east",
    },
    {
        "slug": "timezone",
        "old": "The user's home timezone is America/New_York and meetings are booked in that zone.",
        "new": "The user relocated last month: the current timezone is Europe/Berlin and meetings moved with it.",
        "question": "What timezone is the user in now?",
        "answer": "Europe/Berlin",
    },
    {
        "slug": "runtime",
        "old": "The frontend build runs on npm and the lockfile of record is package-lock.json.",
        "new": "The frontend build has switched to bun 1.1 and the lockfile of record is now bun.lock.",
        "question": "Which runtime and lockfile does the frontend build use now?",
        "answer": "bun 1.1 with bun.lock",
    },
)

UPDATE_DAY = 40.0
QUERY_DAY = 55
FILLER_PER_DAY = 15
FILLER_DAYS = 15
FILLER_TOTAL = FILLER_PER_DAY * FILLER_DAYS


def _build_staleness(rng: random.Random, i: int, with_retirement: bool) -> Scenario:
    """One staleness scenario. ``with_retirement`` is the only difference."""
    case = _STALENESS_CASES[i % len(_STALENESS_CASES)]
    mode = "retire" if with_retirement else "decay"
    sid = "syn-stale-%s-%s-%d" % (mode, case["slug"], i)
    old_id = "%s-old" % sid
    new_id = "%s-new" % sid

    events: List[Event] = [_add(0.0, old_id, case["old"], "general")]
    # It was the right answer for a while, so it earned retrieval strength.
    for when in (2.0, 6.0, 11.0, 19.0, 28.0, 34.0):
        events.append(_access(when, old_id))

    # Fresh filler so the budget is contested; share one ``used`` set so no two
    # filler memories are identical and the store cannot silently shrink.
    used: Set[Tuple] = set()
    for offset in range(FILLER_DAYS):
        events += _noise(rng, FILLER_PER_DAY, UPDATE_DAY + offset,
                         "%s-f%d" % (sid, offset), "general", used)

    events.append(_add(UPDATE_DAY, new_id, case["new"], "general"))
    if with_retirement:
        events.append(Event(op="retire", day=UPDATE_DAY, id=old_id, supersedes=new_id))
    for when in (43.0, 47.0, 52.0):
        events.append(_access(when, new_id))

    queries = [_query(QUERY_DAY, "%s-q1" % sid, case["question"], case["answer"],
                      [new_id], [old_id], kind="staleness")]
    description = ("value superseded after heavy use against %d fresh filler memories%s"
                   % (FILLER_TOTAL, "" if with_retirement else " (no retire event)"))
    return Scenario(sid, "staleness", description, _ordered(events), queries,
                    source="synthetic")


def staleness_suite(seed: int = 0) -> List[Scenario]:
    """Scenarios where a superseded fact competes with its replacement.

    Retire events are emitted, so an arm that supports supersession can drop the
    stale memory. A win here is a SUPERSESSION result - compare against
    ``decay_only_staleness_suite`` before attributing it to decay.
    """
    rng = random.Random(seed)
    return [_build_staleness(rng, i, True) for i in range(len(_STALENESS_CASES))]


def decay_only_staleness_suite(seed: int = 0) -> List[Scenario]:
    """Identical to ``staleness_suite`` but with no retire events or links.

    This isolates whether decay ALONE retires a stale fact. Built by the same
    function as ``staleness_suite``, so the two cannot drift apart.
    """
    rng = random.Random(seed)
    return [_build_staleness(rng, i, False) for i in range(len(_STALENESS_CASES))]


# ------------------------------------------------------------ validation
def _validate_staleness(scenario: Scenario, expect_retirement: bool) -> List[str]:
    problems = _validate(scenario)
    added = sum(1 for e in scenario.events if e.op == "add")
    retired = {e.id for e in scenario.events if e.op == "retire"}
    if added <= 200:
        problems.append("%s: only %d memories, the budget will not bind" % (scenario.id, added))
    if expect_retirement and not retired:
        problems.append("%s: expected retire events" % scenario.id)
    if not expect_retirement and retired:
        problems.append("%s: decay-only suite must not retire anything" % scenario.id)
    for query in scenario.queries:
        for stale in query.stale_ids:
            if expect_retirement and stale not in retired:
                problems.append("%s/%s: stale %s was never retired" % (scenario.id, query.id, stale))
            if not expect_retirement and stale in retired:
                problems.append("%s/%s: stale %s retired in the decay-only suite"
                                % (scenario.id, query.id, stale))
    for event in scenario.events:
        if event.op != "retire":
            continue
        for query in scenario.queries:
            if event.id in query.stale_ids and event.day > query.session:
                problems.append("%s/%s: stale %s retired after the query"
                                % (scenario.id, query.id, event.id))
    # The pair must stay below the engine's duplicate threshold, or collapsing
    # would look like staleness handling.
    contents = {e.id: e.content for e in scenario.events if e.op == "add"}
    for query in scenario.queries:
        for stale in query.stale_ids:
            for evidence in query.evidence_ids:
                if stale in contents and evidence in contents:
                    score = jaccard(set(tokenize(contents[stale])), set(tokenize(contents[evidence])))
                    if score >= 0.9:
                        problems.append("%s/%s: stale/evidence Jaccard %.2f >= 0.9"
                                        % (scenario.id, query.id, score))
    return problems


def _validate(scenario: Scenario) -> List[str]:
    problems: List[str] = []
    added_at: Dict[str, float] = {}
    for event in scenario.events:
        if event.op == "add":
            if event.id in added_at:
                problems.append("%s: duplicate id %s" % (scenario.id, event.id))
            added_at[event.id] = event.timestamp()
    for a, b in zip(scenario.events, scenario.events[1:]):
        if b.day < a.day:
            problems.append("%s: events out of order at day %s" % (scenario.id, b.day))
            break
    for query in scenario.queries:
        when = query.session * 86400.0
        for evidence in query.evidence_ids:
            if evidence not in added_at:
                problems.append("%s/%s: evidence %s was never added" % (scenario.id, query.id, evidence))
            elif added_at[evidence] > when:
                problems.append("%s/%s: evidence %s added after the query" % (scenario.id, query.id, evidence))
        for stale in query.stale_ids:
            if stale not in added_at:
                problems.append("%s/%s: stale %s was never added" % (scenario.id, query.id, stale))
            elif added_at[stale] > when:
                problems.append("%s/%s: stale %s added after the query" % (scenario.id, query.id, stale))
    return problems


